import * as fs from "node:fs/promises";
import * as path from "node:path";
import { build, context } from "esbuild";

const root = process.cwd();
const watch = process.argv.includes("--watch");
const development = process.argv.includes("--dev") || watch;
const output = path.join(root, "dist", development ? "client-dev" : "client");
if (!watch) {
  await fs.rm(output, { recursive: true, force: true });
  await fs.cp(path.join(root, "public"), output, { recursive: true });
}
await fs.mkdir(path.join(output, "assets"), { recursive: true });

const options = {
  absWorkingDir: root,
  entryPoints: {
    entry: "app/assets/entry.ts",
    viewer: "app/assets/viewer.ts",
    editor: "app/assets/editor.ts",
    projects: "app/assets/projects.ts",
    newMap: "app/assets/new-map-setup.tsx",
    recoveredMaps: "app/assets/recovered-maps.tsx",
    hostedProjects: "app/assets/hosted-projects.tsx",
    projectMaps: "app/assets/project-maps.tsx",
  },
  outdir: path.relative(root, path.join(output, "assets")),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  jsx: "automatic",
  jsxImportSource: "remix/ui",
  splitting: !development,
  entryNames: development ? "[name]" : "[name]-[hash]",
  chunkNames: "chunk-[hash]",
  metafile: true,
  sourcemap: true,
  define: { LOCAL_FIXTURES_ENABLED: JSON.stringify(development) },
  plugins: [
    {
      name: "maps-build-manifest",
      setup(buildContext) {
        buildContext.onEnd(async (result) => {
          if (development || result.errors.length || !result.metafile) return;
          const entryHref = (name) => {
            const sourceName =
              name === "newMap"
                ? "new-map-setup.tsx"
                : name === "recoveredMaps"
                  ? "recovered-maps.tsx"
                  : name === "hostedProjects"
                    ? "hosted-projects.tsx"
                    : name === "projectMaps"
                      ? "project-maps.tsx"
                      : `${name}.ts`;
            const entry = Object.entries(result.metafile.outputs).find(
              ([, metadata]) =>
                metadata.entryPoint === `app/assets/${sourceName}`,
            );
            if (!entry)
              throw new Error(`Maps browser build did not emit ${name}`);
            return `/${path.relative(output, path.resolve(root, entry[0])).split(path.sep).join("/")}`;
          };
          await fs.writeFile(
            path.join(root, "app", "assets", "build-manifest.ts"),
            `// Generated by scripts/build.mjs.\nexport const browserAssets = import.meta.env.DEV\n  ? {\n      entry: "/assets/entry.js",\n      viewer: "/assets/viewer.js",\n      editor: "/assets/editor.js",\n      projects: "/assets/projects.js",\n      newMap: "/assets/newMap.js",\n      recoveredMaps: "/assets/recoveredMaps.js",\n      hostedProjects: "/assets/hostedProjects.js",\n      projectMaps: "/assets/projectMaps.js",\n    }\n  : {\n      entry: ${JSON.stringify(entryHref("entry"))},\n      viewer: ${JSON.stringify(entryHref("viewer"))},\n      editor: ${JSON.stringify(entryHref("editor"))},\n      projects: ${JSON.stringify(entryHref("projects"))},\n      newMap: ${JSON.stringify(entryHref("newMap"))},\n      recoveredMaps: ${JSON.stringify(entryHref("recoveredMaps"))},\n      hostedProjects: ${JSON.stringify(entryHref("hostedProjects"))},\n      projectMaps: ${JSON.stringify(entryHref("projectMaps"))},\n    };\n`,
          );
        });
      },
    },
  ],
};

if (watch) {
  const buildContext = await context(options);
  await buildContext.watch();
} else {
  await build(options);
}
