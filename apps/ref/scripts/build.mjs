import * as fs from "node:fs/promises";
import * as path from "node:path";
import { build } from "esbuild";

const root = process.cwd();
const outputDirectory = path.join(root, "dist", "client");
await fs.rm(outputDirectory, { recursive: true, force: true });
await fs.cp(path.join(root, "public"), outputDirectory, { recursive: true });
await fs.mkdir(path.join(outputDirectory, "assets"), { recursive: true });

const result = await build({
  absWorkingDir: root,
  entryPoints: { board: "app/assets/board.ts" },
  outdir: "dist/client/assets",
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  splitting: true,
  entryNames: "[name]-[hash]",
  chunkNames: "chunk-[hash]",
  metafile: true,
  sourcemap: true,
  minify: process.env.NODE_ENV === "production",
});

const entry = Object.entries(result.metafile.outputs).find(
  ([, metadata]) => metadata.entryPoint === "app/assets/board.ts",
);
if (!entry) throw new Error("Board browser build did not emit an entry point");
const href = `/${path.relative(outputDirectory, path.resolve(root, entry[0])).split(path.sep).join("/")}`;
await fs.writeFile(
  path.join(root, "app", "assets", "build-manifest.ts"),
  `// Generated by scripts/build.mjs.\nexport const browserAssets = { board: ${JSON.stringify(href)} } as const;\n`,
);
